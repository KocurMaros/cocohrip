"""Hardware-free tests for the English draughts (WCDF) rules engine + huff rule.

Run:  cd checkers_game && python3 -m pytest test/test_rules.py -q
"""
import random

import pytest

from checkers_game.checkers.rules import (BLACK, DRAW, QUIET_PLY_LIMIT, WHITE,
                                          GameState, Move, huff_candidates)
from checkers_game.minimax.algorithm import choose_huff, choose_move


def pos(text, turn):
    """Board from 8 lines of 8 chars: . empty, w/W white man/king, b/B black."""
    rows = [ln.strip() for ln in text.strip().splitlines()]
    assert len(rows) == 8
    val = {".": 0, "w": 1, "W": 2, "b": -1, "B": -2}
    cells = [val[ch] for row in rows for ch in row.replace(" ", "")]
    return GameState(cells, turn)


def ends(moves):
    return sorted((m.start, m.end) for m in moves)


# ---------------------------------------------------------------- basics
def test_initial_position_counts_and_moves():
    s = GameState.initial()
    assert s.count(WHITE) == 12 and s.count(BLACK) == 12
    assert s.turn == BLACK                     # WCDF: black (dark) moves first
    assert len(s.legal_moves()) == 7
    assert len(s.copy_with(turn=WHITE).legal_moves()) == 7
    for m in s.legal_moves():
        assert m.end[0] == 3                   # black men move "down"


def test_initial_both_parities():
    for parity in (0, 1):
        s = GameState.initial(dark_parity=parity)
        for r, c, _ in s.pieces(WHITE) + s.pieces(BLACK):
            assert (r + c) % 2 == parity


def test_men_move_forward_only_kings_one_square_any_direction():
    s = pos("""
        ........
        ........
        ........
        ....w...
        ........
        ..W.....
        ........
        ........""", WHITE)
    assert ends(s.simple_moves_from(3, 4)) == [((3, 4), (2, 3)), ((3, 4), (2, 5))]
    assert ends(s.simple_moves_from(5, 2)) == sorted(
        [((5, 2), (4, 1)), ((5, 2), (4, 3)), ((5, 2), (6, 1)), ((5, 2), (6, 3))])


# ------------------------------------------------------- mandatory capture
def test_capture_is_mandatory():
    s = pos("""
        ........
        ........
        ...b....
        ....w...
        ........
        ......w.
        ........
        ........""", WHITE)
    moves = s.legal_moves()
    assert len(moves) == 1
    assert moves[0].captured == ((2, 3),) and moves[0].end == (1, 2)


def test_men_cannot_capture_backwards_but_kings_can():
    s = pos("""
        ........
        ........
        ........
        ....w...
        ...b....
        ........
        ........
        ........""", WHITE)
    assert s.all_captures() == []              # black man is behind the white man
    s2 = pos("""
        ........
        ........
        ........
        ....W...
        ...b....
        ........
        ........
        ........""", WHITE)
    caps = s2.all_captures()
    assert len(caps) == 1 and caps[0].end == (5, 2)


def test_multi_jump_must_be_completed_and_can_zigzag():
    s = pos("""
        ........
        ........
        ...b....
        ........
        ...b....
        ..w.....
        ........
        ........""", WHITE)
    caps = s.all_captures()
    assert len(caps) == 1
    m = caps[0]
    assert m.path == ((5, 2), (3, 4), (1, 2))
    assert m.captured == ((4, 3), (2, 3))


def test_player_may_choose_any_capture_no_majority_rule():
    s = pos("""
        ........
        ........
        .b......
        ........
        .b...b..
        w.....w.
        ........
        ........""", WHITE)
    caps = s.all_captures()
    lens = sorted(len(m.captured) for m in caps)
    assert lens == [1, 2]                      # both the single and the double jump


def test_crowning_ends_the_move():
    # white man jumps onto row 0 and could continue as a king - must stop
    s = pos("""
        ........
        ..b.b...
        .....w..
        ........
        ........
        ........
        ........
        ........""", WHITE)
    caps = s.all_captures()
    assert len(caps) == 1 and caps[0].promotes
    after = s.apply(caps[0])
    assert after.at(0, 3) == 2 and after.at(1, 2) == -1   # b at (1,2) survives


def test_multi_jump_landing_on_last_row_is_generated():
    # regression: old _traverse_* used stop=max(r-3,0) and never reached row 0
    s = pos("""
        ........
        .b......
        ........
        ...b....
        ....w...
        ........
        ........
        ........""", WHITE)
    caps = s.all_captures()
    assert len(caps) == 1
    assert caps[0].end == (0, 0) and len(caps[0].captured) == 2 and caps[0].promotes


def test_king_square_loop_captures_four():
    s = pos("""
        ........
        ........
        ........
        ..b.b...
        .W......
        ..b.b...
        ........
        ........""", WHITE)
    caps = s.all_captures()
    best = max(caps, key=lambda m: len(m.captured))
    assert len(best.captured) == 4
    assert len(set(best.captured)) == 4


