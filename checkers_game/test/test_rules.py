def test_quiet_move_draw_rule():
    s = pos("""
        ........
        ........
        ..B.....
        ........
        ........
        .....W..
        ........
        ........""", WHITE)
    s = s.copy_with(quiet_plies=QUIET_PLY_LIMIT)
    assert s.winner() == DRAW
    # a man move resets the counter
    s2 = pos("""
        ........
        ........
        ..B.....
        ........
        ........
        .....w..
        ........
        ........""", WHITE).copy_with(quiet_plies=10)
    assert s2.apply(s2.legal_moves()[0]).quiet_plies == 0


# ------------------------------------------------------------- huff rule
def test_huff_non_capture_move():
    s = pos("""
        ........
        ........
        ...b....
        ....w...
        ........
        ......w.
        ........
        ........""", WHITE)
    m = Move(((5, 6), (4, 5)))
    cls = s.classify_move(m)
    assert cls.kind == "huff"
    assert cls.huff_squares == [(3, 4)]        # the piece that should have jumped


def test_huff_when_capturing_piece_itself_moves_away():
    s = pos("""
        ........
        ........
        ...b....
        ....w...
        ........
        ........
        ........
        ........""", WHITE)
    m = Move(((3, 4), (2, 5)))
    cls = s.classify_move(m)
    assert cls.kind == "huff"
    assert cls.huff_squares == [(2, 5)]        # huffed at its new square


def test_huff_incomplete_multi_jump():
    s = pos("""
        ........
        ........
        ...b....
        ........
        ...b....
        ..w.....
        ........
        ........""", WHITE)
    partial = Move(((5, 2), (3, 4)), ((4, 3),))
    cls = s.classify_move(partial)
    assert cls.kind == "huff"
    assert cls.huff_squares == [(3, 4)]


def test_illegal_moves_are_not_huffable():
    s = GameState.initial(turn=WHITE)
    back = Move(((5, 0), (6, 1)))              # backwards / occupied
    two = Move(((5, 0), (3, 2)))               # 2 squares without capture
    assert s.classify_move(back).kind == "illegal"
    assert s.classify_move(two).kind == "illegal"
    ok = s.legal_moves()[0]
    assert s.classify_move(ok).kind == "legal"


def test_no_huff_possible_without_available_capture():
    s = GameState.initial(turn=WHITE)
    assert s.huffable_moves() == []


# ----------------------------------------------------------------- AI
def test_ai_always_captures_and_completes_multi_jump():
    s = pos("""
        ........
        ........
        .b......
        ..w.....
        ........
        ..w.....
        ........
        ........""", BLACK)
    m, _, _ = choose_move(s, level=3, rng=random.Random(0))
    assert m.captured == ((3, 2), (5, 2)) or len(m.captured) == 2
    assert m in s.legal_moves()


def test_ai_returns_none_when_no_moves():
    s = pos("""
        b.......
        .w......
        ..w.....
        ........
        ........
        ........
        ........
        ........""", BLACK)
    m, _, _ = choose_move(s, level=3)
    assert m is None


def test_ai_plays_full_random_games_legally():
    rng = random.Random(1)
    for game in range(3):
        s = GameState.initial()
        for ply in range(200):
            if s.winner() is not None:
                break
            if s.turn == BLACK:
                m, _, _ = choose_move(s, level=2, time_limit=0.5, rng=rng)
            else:
                m = rng.choice(s.legal_moves())
            assert m in s.legal_moves()
            s = s.apply(m)


def test_choose_huff_returns_candidate():
    s = pos("""
        ........
        ........
        ...b....
        ....w...
        ........
        ......w.
        ...w....
        ........""", WHITE)
    m = Move(((6, 3), (5, 2)))
    cls = s.classify_move(m)
    after = s.apply(m)
    sq = choose_huff(after, cls.huff_squares, level=2)
    assert sq in cls.huff_squares


def test_huff_candidates_lists_all_capturers():
    s = pos("""
        ........
        ........
        ...b.b..
        ....w...
        ........
        ..w.....
        ........
        ........""", WHITE)
    m = Move(((5, 2), (4, 1)))
    assert huff_candidates(s, m) == [(3, 4)]


@pytest.mark.parametrize("level", [1, 3, 5])
def test_ai_levels_run(level):
    s = GameState.initial()
    m, _, _ = choose_move(s, level=level, time_limit=2.0)
    assert m in s.legal_moves()
